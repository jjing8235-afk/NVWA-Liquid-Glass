import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const source=fs.readFileSync(path.join(root,'index.js'),'utf8');
const defaults=source.match(/const DEFAULTS = (\{[\s\S]*?\n\});/)[1];
const values=vm.runInNewContext('('+defaults+')',{PRESETS:{depth:['',{}],natural:['',{}]}});
assert.equal(values.chatFontSize,0);
const normalizer=source.match(/function normalizeChatFontSize\(value\) \{([\s\S]*?)\n\}/)[0];
const normalize=vm.runInNewContext('('+normalizer+')');
for(const [raw,wanted]of [[undefined,0],[null,0],['',0],['invalid',0],[Infinity,0],[-5,0],[0,0],[5,12],[12,12],[19.6,20],['24',24],[999,32]])assert.equal(normalize(raw),wanted);
const merge=source.match(/ctx\.extensionSettings\[MODULE\] = (Object\.assign\([^;]+\));/)[1];
const ctx={extensionSettings:{test:{unknown:'keep',chatFontSize:24}}};
const merged=vm.runInNewContext(merge,{ctx,MODULE:'test',DEFAULTS:values});
assert.equal(merged.chatFontSize,24);assert.equal(merged.unknown,'keep');
const fontHandler=source.match(/const saveChatFont = value => \{([\s\S]*?)\n    \};/)[1];
assert(!/applyRoot|clearAll|repaintAll|queueCards/.test(fontHandler));
assert(source.includes('S.chatFontSize = normalizeChatFontSize(S.chatFontSize);'));
console.log(JSON.stringify({passed:['Follow-host default and safe imported values','Range limits and pixel rounding','Unknown settings preserved','Font controls do not reinitialize all glass']},null,2));
