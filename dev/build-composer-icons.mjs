// Rebuild bundled Ionicons outline masks without runtime network access.
import fs from 'node:fs/promises';
const data=JSON.parse(await fs.readFile(new URL('./assets/ionicons-composer.json',import.meta.url),'utf8'));
const uri=svg=>'url("data:image/svg+xml;base64,'+Buffer.from(svg).toString('base64')+'")';
const css='/* Ionicons 7.4.0 (MIT). See LICENSE-ionicons.txt. Generated by dev/build-composer-icons.mjs. */\nhtml.ilg {\n'+Object.entries(data.icons).map(([key,value])=>'    --ilg-ui-'+key+': '+uri(value.svg)+';').join('\n')+'\n}\n';
await fs.writeFile(new URL('../composer-icons.css',import.meta.url),css);
console.log('Wrote '+Object.keys(data.icons).length+' iOS-style outline icons.');
